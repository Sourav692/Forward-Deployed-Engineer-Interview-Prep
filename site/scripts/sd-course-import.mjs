/** Where an anchor of stage `stage` lands: `{ part, section }`, section null for the part top. */
function findAnchor(stage, anchor) {
  for (const part of stage.parts) {
    if ([githubSlug(part.heading), tocSlug(part.heading)].includes(anchor)) return { part, section: null }
    for (const h of part.sections) {
      if ([githubSlug(h.text), tocSlug(h.text)].includes(anchor)) return { part, section: h.section }
    }
  }
  return null
}

