/**
 * Splits the AI System Design course (`10_AI_System_Design/stages/NN-<stage>/guide.md`, Stages 0
 * to 12) into site lessons in `01_Concept_Tutorials/AI_System_Design_Course/` (plan
 * .website_spec/status/in-progress/implementation_plan_ai-system-design-course.md, task SDC-02).
 * The course folder stays the place to edit them; this copy is regenerated, never edited.
 *
 *   npm run import:sd-course
 *
 * Every guide has the same five `## N. <part>` headings. Each part becomes one file,
 * `NN_<stage>/0K_<part>.md`, titled "<Stage title>: <part title>", with its headings promoted one
 * level so the site's `## ` sections work. The text before the first part opens part 1.
 * Transforms:
 *  - a link to a stage guide (`guide.md` or `guide.html`, this stage's or another's) becomes a
 *    relative link to the part file that holds the target, with the site's `lesson-…` id of the
 *    `## ` section around the target heading;
 *  - the stage's interactive parts (the request walkthrough, the lab experiment and Stage 0's
 *    architecture map, HTML-only anchors `#request-walkthrough`, `#lab`, `#target-map`) are cut from
 *    its `guide.html` into `site/public/labs/system-design/NN_<stage>/lab.html` (task SDC-03): the
 *    blocks, their JSON config and the inline script, on the site's lab tokens through
 *    `siteLab()`, which fails on any request. Links to those anchors go to the lab, and a ```lab
 *    fence follows the first paragraph that links it in each part;
 *  - a link to any other course file (labs, ADRs, validation, progress records) becomes a GitHub
 *    link, since learn.mjs turns a repository path into plain text;
 *  - the "Complete Stage Package" subsection and every sentence about the stage ZIP or its
 *    clean-extraction checks go: the site offers no ZIP (owner decision, 3 November 2026);
 *  - stage and part titles take sentence case and British spelling (src/lib/spelling.ts).
 * The import fails on a link or anchor that resolves to nothing, on a placeholder (TODO, TBD,
 * XXX, [FILL) and when the course stages have uncommitted changes, so `source.json` names the
 * exact commit. A second run on an unchanged course gives no diff.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, posix, relative, resolve, sep } from 'node:path'
import { githubSlug, readingSlug } from './learn.mjs'
import { britishText, siteLab } from './rag-theory-import.mjs'

const SITE = resolve(import.meta.dirname, '..')
const REPO_ROOT = resolve(SITE, '..')
const COURSE = '10_AI_System_Design'
const OUT_REL = '01_Concept_Tutorials/AI_System_Design_Course'
const LABS_REL = 'site/public/labs/system-design'
// The Learn track the lessons publish in (task SDC-05: site/src/lib/sd-course.ts). Its module slugs
// are the stage folder names without their number, and each stage opens on part 1.
const TRACK = 'staff-ai-system-design'
const stageLessonUrl = (dir) => {
  const slug = dir.replace(/^\d{2}-/, '')
  return `/learn/${TRACK}/${slug}/${slug}-understand-the-problem`
}
const GITHUB = 'https://github.com/Sourav692/Forward-Deployed-Engineer-Interview-Prep/blob/main'
const HEADER = `<!-- Generated by site/scripts/sd-course-import.mjs from ${COURSE}. Edit the stage guide there. -->\n`
const PLACEHOLDER = /\[FILL\b|\bTODO\b|\bTBD\b|\bXXX\b/
const DROPPED_SECTIONS = ['Complete Stage Package']
// The course's interactive blocks, by the id its guide.html gives them, in lab-page order.
const LAB_ANCHORS = ['target-map', 'request-walkthrough', 'lab']
// Sentences about the stage ZIP and its clean-extraction checks; the site offers no ZIP.
const PACKAGE_SENTENCE = /\b(complete|full) (package|archive|ZIP)\b|\bclean[ -]extraction\b/i
const posixPath = (p) => p.split(sep).join('/')

// ------------------------------------------------------------------ text helpers

/** "Handle Overload and Fair Scheduling" → "Handle overload and fair scheduling"; acronyms stay. */
export function sentenceCase(title) {
  const lower = (word) => (/^[A-Z0-9]{2,}s?$/.test(word) ? word : word.toLowerCase())
  const text = title
    .split(' ')
    .map((word) => word.split('-').map(lower).join('-'))
    .join(' ')
  return britishText(text.charAt(0).toUpperCase() + text.slice(1))
}

/** The anchor python-markdown's toc extension gives a heading (the course renders its HTML with it). */
const tocSlug = (text) =>
  text
    .normalize('NFKD')
    .replace(/[^\x00-\x7f]/g, '')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .toLowerCase()
    .replace(/[-\s]+/g, '-')

/** Calls `fn(line, index)` for each line outside fenced code blocks. */
function eachProseLine(lines, fn) {
  let fence = null
  lines.forEach((line, i) => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/)
    if (fence) {
      if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length) fence = null
      return
    }
    if (marker) fence = marker[1]
    else fn(line, i)
  })
}

const HEADING = /^(#{1,6})\s+(.*?)\s*#*\s*$/

// ------------------------------------------------------------------ parse

/**
 * One stage: its folder, title, preamble and five parts. Each part keeps its lines (part heading
 * removed, sections in DROPPED_SECTIONS cut) and the original headings it holds.
 */
function parseStage(dir) {
  const rel = `${COURSE}/stages/${dir}`
  const lines = readFileSync(join(REPO_ROOT, rel, 'guide.md'), 'utf8').split('\n')
  const h1 = lines[0].match(/^# Stage (\d+): (.+)$/)
  if (!h1) throw new Error(`${rel}/guide.md: first line is not "# Stage N: <title>"`)
  const starts = []
  eachProseLine(lines, (line, i) => {
    const m = line.match(/^## (\d+)\. (.+)$/)
    if (m) starts.push({ i, n: Number(m[1]), title: m[2] })
  })
  if (starts.length !== 5 || starts.some((s, k) => s.n !== k + 1)) {
    throw new Error(`${rel}/guide.md: expected "## 1." to "## 5." part headings, found ${starts.map((s) => s.n).join(', ')}`)
  }
  const parts = starts.map((s, k) => {
    const body = dropSections(lines.slice(s.i + 1, starts[k + 1]?.i ?? lines.length))
    return { n: s.n, heading: `${s.n}. ${s.title}`, title: sentenceCase(s.title), lines: body, sections: sectionsOf(body) }
  })
  return {
    dir,
    rel,
    out: dir.replace(/-/g, '_'),
    title: sentenceCase(h1[2]),
    preamble: lines.slice(1, starts[0].i),
    parts,
  }
}

/** Cuts each heading in DROPPED_SECTIONS with everything under it. */
function dropSections(lines) {
  // `cut` is the level of the dropped heading while inside its section; fenced lines follow it.
  const prose = new Set()
  eachProseLine(lines, (_, i) => prose.add(i))
  let cut = null
  return lines.filter((line, i) => {
    const m = prose.has(i) && line.match(HEADING)
    if (m && cut && m[1].length <= cut) cut = null
    if (m && DROPPED_SECTIONS.includes(m[2])) cut = m[1].length
    return !cut
  })
}

/** Each original heading of a part body (### and deeper) with the `### ` section that holds it. */
function sectionsOf(lines) {
  const out = []
  let section = null
  eachProseLine(lines, (line) => {
    const m = line.match(HEADING)
    if (!m) return
    if (m[1].length === 3) section = m[2]
    out.push({ level: m[1].length, text: m[2], section })
  })
  return out
}

// ------------------------------------------------------------------ links

/** Where an anchor of stage `stage` lands: `{ part, section }`, section null for the part top. */
function findAnchor(stage, anchor) {
  for (const part of stage.parts) {
    if ([githubSlug(part.heading), tocSlug(part.heading)].includes(anchor)) return { part, section: null }
    for (const h of part.sections) {
      if ([githubSlug(h.text), tocSlug(h.text)].includes(anchor)) return { part, section: h.section }
    }
  }
  return null
}

/** "Build the MVP: think like a staff engineer": the file H1 and the curriculum lesson title. */
export const lessonTitle = (stage, part) => `${stage.title}: ${part.title.charAt(0).toLowerCase()}${part.title.slice(1)}`

const labHref = (stage) => `/labs/system-design/${stage.out}/lab.html`

const sectionId = (section) => (section ? `#lesson-${readingSlug(section) || 'section'}` : '')
const partFile = (stage, part) => `${stage.out}/0${part.n}_${part.title.toLowerCase().replace(/[^a-z0-9]+/g, '_')}.md`

/** Rewrites every Markdown link of one part body. */
function rewriteLinks(lines, ctx) {
  const { stage, part, stagesByDir } = ctx
  const here = partFile(stage, part)
  const out = [...lines]
  eachProseLine(lines, (line, i) => {
    out[i] = line.replace(/(!?)\[([^\]]*)\]\(([^)]+)\)/g, (all, bang, text, target) => {
      if (bang) throw new Error(`${stage.rel}/guide.md: images are not supported: ${all}`)
      if (/^(https?:|mailto:)/.test(target)) return all
      if (/\s/.test(target)) throw new Error(`${stage.rel}/guide.md: link target with a space: ${all}`)
      const [path, anchor] = target.split('#')
      const abs = path ? resolve(REPO_ROOT, stage.rel, path) : resolve(REPO_ROOT, stage.rel, 'guide.md')
      const repoPath = posixPath(relative(REPO_ROOT, abs))
      const guide = repoPath.match(new RegExp(`^${COURSE}/stages/([^/]+)/guide\\.(md|html)$`))
      if (guide) {
        const dest = stagesByDir.get(guide[1])
        if (!dest) throw new Error(`${stage.rel}/guide.md: link to unknown stage: ${all}`)
        if (LAB_ANCHORS.includes(anchor)) return `[${text}](${labHref(dest)}#${anchor})`
        const spot = anchor ? findAnchor(dest, anchor) : { part: dest.parts[0], section: null }
        if (!spot) throw new Error(`${stage.rel}/guide.md: anchor #${anchor} not found in ${dest.rel}/guide.md: ${all}`)
        const file = partFile(dest, spot.part)
        const rel = file === here ? '' : posix.relative(posix.dirname(here), file)
        return `[${text}](${rel}${sectionId(spot.section)})`
      }
      if (!existsSync(abs) || !statSync(abs).isFile()) throw new Error(`${stage.rel}/guide.md: link to a missing file: ${all}`)
      if (anchor !== undefined) throw new Error(`${stage.rel}/guide.md: anchors into non-guide files are not supported: ${all}`)
      return `[${text}](${GITHUB}/${repoPath})`
    })
  })
  return out
}

/** Promotes headings one level (### → ##) outside code fences. */
function promote(lines) {
  const out = [...lines]
  eachProseLine(lines, (line, i) => {
    if (/^#{3,6}\s/.test(line)) out[i] = line.slice(1)
  })
  return out
}

/** Drops PACKAGE_SENTENCE sentences from prose lines (not headings or table rows). */
function dropPackageSentences(lines) {
  const out = [...lines]
  eachProseLine(lines, (line, i) => {
    if (!PACKAGE_SENTENCE.test(line) || /^(#|\|)/.test(line)) return
    out[i] = line
      .split(/(?<=[.!?])\s+(?=[A-Z[`])/)
      .filter((sentence) => !PACKAGE_SENTENCE.test(sentence))
      .join(' ')
  })
  return out
}

// ------------------------------------------------------------------ labs

/** The element that starts at `start` (`<name …`), up to its matching close tag. */
function element(html, start, name, where) {
  const tags = new RegExp(`<${name}\\b|</${name}>`, 'g')
  tags.lastIndex = start
  let depth = 0
  for (let m; (m = tags.exec(html)); ) {
    depth += m[0][1] === '/' ? -1 : 1
    if (!depth) return html.slice(start, m.index + m[0].length)
  }
  throw new Error(`${where}: <${name}> at ${start} is never closed`)
}

const plainText = (html) => html.replace(/<[^>]*>/g, '').replace(/&amp;/g, '&').trim()
const escapeHtml = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;')

/** Maps the course's CSS variables to the site lab tokens (site/public/labs/_site-tokens.css). */
const LAB_STYLE = `:root{--paper:var(--color-paper);--surface:var(--color-paper-2);--ink:var(--color-ink);--muted:var(--color-muted);--line:var(--color-rule);--accent:var(--color-accent);--on-accent:var(--color-accent-ink);--focus:var(--color-focus);--font-code:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}
body{margin:0;background:var(--paper);color:var(--ink);font-family:var(--font-body)}
main.lab{max-width:60rem;margin:0 auto;padding:2rem 1.25rem 4rem}
main.lab h1{font-family:var(--font-display);font-size:clamp(1.75rem,4vw,2.5rem);line-height:1.1;margin:0 0 .75rem}
main.lab>p{max-width:75ch;color:var(--muted)}
main.lab h2{font-family:var(--font-display);font-size:1.4rem;margin:2.5rem 0 1rem}`

/**
 * A stage's lab page: its interactive blocks cut from guide.html (each heading's following
 * element, or the Stage 0 map figure), the JSON config and inline script, on the site tokens.
 * Null when the stage has none.
 */
function buildLab(stage) {
  const where = `${stage.rel}/guide.html`
  const html = readFileSync(join(REPO_ROOT, where), 'utf8')
  const blocks = []
  for (const anchor of LAB_ANCHORS) {
    const tag = html.match(new RegExp(`<(h[2-6]|figure)\\b[^>]*\\bid="${anchor}"[^>]*>`))
    if (!tag) continue
    if (tag[1] === 'figure') {
      blocks.push({ anchor, title: 'Architecture map', body: element(html, tag.index, 'figure', where) })
      continue
    }
    const close = html.indexOf(`</${tag[1]}>`, tag.index)
    const after = html.slice(close + tag[1].length + 3).match(/^\s*<div\b/)
    if (!after) throw new Error(`${where}: #${anchor} is not followed by its interactive <div>`)
    const start = close + tag[1].length + 3 + after[0].length - 4
    const title = plainText(html.slice(tag.index + tag[0].length, close))
    blocks.push({ anchor, title: title === 'Request Walkthrough' ? 'Request walkthrough' : title, body: element(html, start, 'div', where) })
  }
  if (!blocks.length) return null
  const style = html.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/@font-face\s*\{[^}]*\}/g, '')
  const scripts = [...html.matchAll(/<script\b[^>]*>[\s\S]*?<\/script>/g)].map((m) => relink(m[0], where))
  for (const b of blocks) b.body = relink(b.body, where)
  const what = blocks.some((b) => b.anchor === 'target-map') ? 'request walkthrough and architecture map' : 'request walkthrough and lab'
  const title = `${stage.title}: ${what}`
  const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<!-- Generated by site/scripts/sd-course-import.mjs from ${where}. Edit the course there. -->
<style>${style}</style>
<style>${LAB_STYLE}</style>
</head>
<body>
<main class="lab" id="content">
<h1>${escapeHtml(title)}</h1>
<p>Part of the Staff AI System Design course. Everything runs in your browser and makes no network requests. Every figure is illustrative.</p>
${blocks.map((b) => `<section aria-labelledby="${b.anchor}">\n<h2 id="${b.anchor}">${escapeHtml(b.title)}</h2>\n${b.body}\n</section>`).join('\n')}
</main>
${scripts.join('\n')}
</body>
</html>
`
  return { title, html: siteLab(page, where), anchors: blocks.map((b) => b.anchor) }
}

/** Stage 0's map links each stage guide (a static href and the paths in its JSON config). */
function relink(html, where) {
  const out = html.replace(/(?:\.\.\/)?(\d{2}-[a-z-]+)\/guide\.(?:html|md)/g, (_, dir) => stageLessonUrl(dir))
  const relative = out.match(/\shref="(?![/#]|https?:)[^"]*"/)
  if (relative) throw new Error(`${where}: lab keeps a relative link (${relative[0].trim()}), which breaks under /labs/`)
  return out
}

/** Adds a ```lab fence after the first paragraph of a part that links its stage's lab. */
function addLabFence(lines, stage, lab) {
  const href = `](${labHref(stage)}#`
  let at = -1
  eachProseLine(lines, (line, i) => {
    if (at === -1 && line.includes(href)) at = i
  })
  if (at === -1) return lines
  let end = at
  while (end + 1 < lines.length && lines[end + 1].trim() !== '') end++
  return [...lines.slice(0, end + 1), '', '```lab', `src: ${labHref(stage)}`, `title: ${lab.title}`, '```', ...lines.slice(end + 1)]
}

/** Trims blank lines at both ends and collapses runs of blank lines. */
const tidy = (lines) => lines.join('\n').replace(/\n{3,}/g, '\n\n').trim()

// ------------------------------------------------------------------ import

function courseCommit() {
  const git = (...args) => execFileSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8' }).trim()
  const dirty = git('status', '--porcelain', '--', `${COURSE}/stages`)
  if (dirty) throw new Error(`${COURSE}/stages has uncommitted changes; commit them first so source.json names the exact commit:\n${dirty}`)
  return git('log', '-1', '--format=%H', '--', COURSE)
}

export function importCourse() {
  const commit = courseCommit()
  const dirs = readdirSync(join(REPO_ROOT, COURSE, 'stages'))
    .filter((d) => /^\d{2}-/.test(d) && existsSync(join(REPO_ROOT, COURSE, 'stages', d, 'guide.md')))
    .sort()
  const stages = dirs.map(parseStage)
  const stagesByDir = new Map(stages.map((s) => [s.dir, s]))

  const files = new Map()
  const labs = new Map()
  for (const stage of stages) {
    const lab = buildLab(stage)
    if (lab) labs.set(stage.out, lab.html)
    let linked = false
    for (const part of stage.parts) {
      const body = [...(part.n === 1 ? stage.preamble : []), ...part.lines]
      let lines = dropPackageSentences(rewriteLinks(body, { stage, part, stagesByDir }))
      for (const [, anchor] of lines.join('\n').matchAll(new RegExp(`\\]\\(${labHref(stage)}#([a-z-]+)\\)`, 'g'))) {
        if (!lab?.anchors.includes(anchor)) throw new Error(`${stage.rel}/guide.md: links #${anchor}, which its guide.html has no interactive block for`)
        linked = true
      }
      if (lab) lines = addLabFence(lines, stage, lab)
      const text = tidy(promote(lines))
      const markdown = `${HEADER}# ${lessonTitle(stage, part)}\n\n${text}\n`
      const hit = markdown.match(PLACEHOLDER)
      if (hit) throw new Error(`${stage.rel}/guide.md, part ${part.n}: placeholder "${hit[0]}"`)
      files.set(partFile(stage, part), markdown)
    }
    if (lab && !linked) throw new Error(`${stage.rel}/guide.md: never links its lab, so no lesson would show it`)
  }

  const out = join(REPO_ROOT, OUT_REL)
  rmSync(out, { recursive: true, force: true })
  for (const [file, markdown] of files) {
    mkdirSync(dirname(join(out, file)), { recursive: true })
    writeFileSync(join(out, file), markdown)
  }
  const source = {
    course: COURSE,
    commit,
    stages: stages.map((s) => ({ dir: s.dir, title: s.title, lessons: s.parts.map((p) => ({ file: partFile(s, p), title: lessonTitle(s, p) })) })),
  }
  writeFileSync(join(out, 'source.json'), `${JSON.stringify(source, null, 2)}\n`)
  const labsOut = join(REPO_ROOT, LABS_REL)
  rmSync(labsOut, { recursive: true, force: true })
  for (const [dir, html] of labs) {
    mkdirSync(join(labsOut, dir), { recursive: true })
    writeFileSync(join(labsOut, dir, 'lab.html'), html)
  }
  return { stages: stages.length, lessons: files.size, labs: labs.size, commit }
}

if (import.meta.main) {
  const r = importCourse()
  console.log(`sd-course import: ${r.lessons} lessons and ${r.labs} labs from ${r.stages} stages at ${r.commit.slice(0, 8)} into ${OUT_REL}/ and ${LABS_REL}/`)
}
