/**
 * A stage's lab page: its interactive blocks cut from guide.html (each heading's following
 * element, or the Stage 0 map figure), the JSON config and inline script, on the site tokens.
 * Null when the stage has none.
 */
function buildLab(stage) {
  const where = `${stage.rel}/guide.html`
  const html = readFileSync(join(REPO_ROOT, where), 'utf8')
  const blocks = []
  for (const anchor of LAB_ANCHORS) {
    const tag = html.match(new RegExp(`<(h[2-6]|figure)\\b[^>]*\\bid="${anchor}"[^>]*>`))
    if (!tag) continue
    if (tag[1] === 'figure') {
      blocks.push({ anchor, title: 'Architecture map', body: element(html, tag.index, 'figure', where) })
      continue
    }
    const close = html.indexOf(`</${tag[1]}>`, tag.index)
    const after = html.slice(close + tag[1].length + 3).match(/^\s*<div\b/)
    if (!after) throw new Error(`${where}: #${anchor} is not followed by its interactive <div>`)
    const start = close + tag[1].length + 3 + after[0].length - 4
    const title = plainText(html.slice(tag.index + tag[0].length, close))
    blocks.push({ anchor, title: title === 'Request Walkthrough' ? 'Request walkthrough' : title, body: element(html, start, 'div', where) })
  }
  if (!blocks.length) return null
  const style = html.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/@font-face\s*\{[^}]*\}/g, '')
  const scripts = [...html.matchAll(/<script\b[^>]*>[\s\S]*?<\/script>/g)].map((m) => relink(m[0], where))
  for (const b of blocks) b.body = relink(b.body, where)
  const what = blocks.some((b) => b.anchor === 'target-map') ? 'request walkthrough and architecture map' : 'request walkthrough and lab'
  const title = `${stage.title}: ${what}`
  const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<!-- Generated by site/scripts/sd-course-import.mjs from ${where}. Edit the course there. -->
<style>${style}</style>
<style>${LAB_STYLE}</style>
</head>
<body>
<main class="lab" id="content">
<h1>${escapeHtml(title)}</h1>
<p>Part of the Staff AI System Design course. Everything runs in your browser and makes no network requests. Every figure is illustrative.</p>
${blocks.map((b) => `<section aria-labelledby="${b.anchor}">\n<h2 id="${b.anchor}">${escapeHtml(b.title)}</h2>\n${b.body}\n</section>`).join('\n')}
</main>
${scripts.join('\n')}
</body>
</html>
`
  return { title, html: siteLab(page, where), anchors: blocks.map((b) => b.anchor) }
}

/** Stage 0's map links each stage guide (a static href and the paths in its JSON config). */
function relink(html, where) {
  const out = html.replace(/(?:\.\.\/)?(\d{2}-[a-z-]+)\/guide\.(?:html|md)/g, (_, dir) => stageLessonUrl(dir))
  const relative = out.match(/\shref="(?![/#]|https?:)[^"]*"/)
  if (relative) throw new Error(`${where}: lab keeps a relative link (${relative[0].trim()}), which breaks under /labs/`)
  return out
}

/** Adds a ```lab fence after the first paragraph of a part that links its stage's lab. */
function addLabFence(lines, stage, lab) {
  const href = `](${labHref(stage)}#`
  let at = -1
  eachProseLine(lines, (line, i) => {
    if (at === -1 && line.includes(href)) at = i
  })
  if (at === -1) return lines
  let end = at
  while (end + 1 < lines.length && lines[end + 1].trim() !== '') end++
  return [...lines.slice(0, end + 1), '', '```lab', `src: ${labHref(stage)}`, `title: ${lab.title}`, '```', ...lines.slice(end + 1)]
}

// ------------------------------------------------------------------ code lab

const TOOLING = ['verify_package.py']
const TEST_COMMAND = /^python3 10_AI_System_Design\/stages\/[^/]+\/labs\/test_\w+\.py$/

/** The stage's Python lab files, lab code first, then tests; empty when it has none. */
function labFiles(stage) {
  const dir = join(REPO_ROOT, stage.rel, 'labs')
  if (!existsSync(dir)) return []
  const files = readdirSync(dir).filter((f) => f.endsWith('.py') && !TOOLING.includes(f))
  return [...files.filter((f) => !f.startsWith('test_')).sort(), ...files.filter((f) => f.startsWith('test_')).sort()]
}

/**
 * Inserts the "Run the code lab" section at the stage's test command (lines before heading
 * promotion, so the section heading is written `### `). A one-line run instruction ending in ":"
 * right above the command is replaced; other prose above it stays. When the command sits directly
 * under a heading, that heading keeps the section and no new one is added. Returns null when this
 * part has no test command.
 */
function addCodeLab(lines, stage, files) {
  const at = lines.findIndex((line, i) => /^```(bash|sh)?$/.test(line.trim()) && TEST_COMMAND.test(lines[i + 1] ?? ''))
  if (at === -1) return null
  let start = at
  let above = at - 1
  while (above >= 0 && !lines[above].trim()) above--
  if (above >= 0 && lines[above].trim().endsWith(':') && !HEADING.test(lines[above]) && !lines[above - 1]?.trim()) start = above
  let before = start - 1
  while (before >= 0 && !lines[before].trim()) before--
  const underHeading = before >= 0 && HEADING.test(lines[before])
  const close = lines.indexOf('```', at + 1)
  const command = lines.slice(at, close + 1).map((line) => (TEST_COMMAND.test(line) ? `${line} -v` : line))
  const section = [
    ...(underHeading ? [] : ['### Run the code lab', '']),
    "Run this stage's Python lab in your terminal to see each idea in the stage hold. It needs Python 3.10 or later and nothing else: the standard library and SQLite only.",
    '',
    '| File | What it is |',
    '| --- | --- |',
    ...files.map((f) => `| [${f}](${GITHUB}/${stage.rel}/labs/${f}) | ${f.startsWith('test_') ? 'Tests: one test per behaviour this stage teaches' : 'Lab code: read this first'} |`),
    '',
    'From the root of your local clone of the repository, run:',
    '',
    ...command,
    '',
    '`-v` prints one line per test, and each test name states one behaviour. Read a test, change one value in the lab code, predict which test fails, and run it again.',
  ]
  return [...lines.slice(0, start), ...section, ...lines.slice(close + 1)]
}

/** Drops the course's Node simulator checks from command blocks: the site's labs are Python only. */
const dropNodeChecks = (lines) => lines.filter((line) => !/^node 10_AI_System_Design\/tools\/test_simulator\.cjs\b/.test(line))

/** Escapes `;` in Mermaid sequence-diagram messages (the text after the arrow's `:`). */
function escapeSequenceSemicolons(lines) {
  const out = [...lines]
  let sequence = false
  let inMermaid = false
  lines.forEach((line, i) => {
    if (/^```mermaid\s*$/.test(line.trim())) [inMermaid, sequence] = [true, false]
    else if (inMermaid && line.trim() === '```') inMermaid = false
    else if (inMermaid && line.trim() === 'sequenceDiagram') sequence = true
    else if (inMermaid && sequence && /--?>>?|-[x)]/.test(line)) {
      const colon = line.indexOf(':')
      if (colon !== -1) out[i] = line.slice(0, colon + 1) + line.slice(colon + 1).replace(/;/g, '#59;')
    }
  })
  return out
}

/** British spelling for prose, leaving code spans, link targets, URLs and HTML tags alone. */
function britishProse(lines) {
  const out = [...lines]
  eachProseLine(lines, (line, i) => {
    out[i] = line
      .split(/(`[^`]*`|\]\([^)]*\)|<[^>]+>|https?:\/\/\S+)/)
      .map((piece, k) => (k % 2 ? piece : britishText(piece)))
      .join('')
  })
  return out
}

/** Every relative link and anchor of the generated files resolves, or the import fails. */
function checkLinks(files) {
  for (const [file, markdown] of files) {
    for (const [, target] of markdown.matchAll(/\]\(((?!https?:|\/)[^)]*)\)/g)) {
      const [path, anchor] = target.split('#')
      const dest = path ? posix.join(posix.dirname(file), path) : file
      if (!files.has(dest)) throw new Error(`${OUT_REL}/${file}: link to a missing lesson file: ${target}`)
      if (anchor && !headingAnchors(files.get(dest)).has(anchor)) throw new Error(`${OUT_REL}/${file}: anchor not found: ${target}`)
    }
  }
}

/** Trims blank lines at both ends and collapses runs of blank lines. */
const tidy = (lines) => lines.join('\n').replace(/\n{3,}/g, '\n\n').trim()

// ------------------------------------------------------------------ import

function courseCommit() {
  const git = (...args) => execFileSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8' }).trim()
  const dirty = git('status', '--porcelain', '--', `${COURSE}/stages`)
  if (dirty) throw new Error(`${COURSE}/stages has uncommitted changes; commit them first so source.json names the exact commit:\n${dirty}`)
  return git('log', '-1', '--format=%H', '--', COURSE)
}

export function importCourse() {
  const commit = courseCommit()
  const dirs = readdirSync(join(REPO_ROOT, COURSE, 'stages'))
    .filter((d) => /^\d{2}-/.test(d) && existsSync(join(REPO_ROOT, COURSE, 'stages', d, 'guide.md')))
    .sort()
  const stages = dirs.map(parseStage)
  const stagesByDir = new Map(stages.map((s) => [s.dir, s]))

  const files = new Map()
  const labs = new Map()
  for (const stage of stages) {
    const lab = buildLab(stage)
    if (lab) labs.set(stage.out, lab.html)
    let linked = false
    const pyFiles = labFiles(stage)
    let codeLab = false
    for (const part of stage.parts) {
      const body = [...(part.n === 1 ? stage.preamble : []), ...part.lines]
      let lines = dropPackageSentences(rewriteLinks(body, { stage, part, stagesByDir }))
      for (const [, anchor] of lines.join('\n').matchAll(new RegExp(`\\]\\(${labHref(stage)}#([a-z-]+)\\)`, 'g'))) {
        if (!lab?.anchors.includes(anchor)) throw new Error(`${stage.rel}/guide.md: links #${anchor}, which its guide.html has no interactive block for`)
        linked = true
      }
      if (lab) lines = addLabFence(lines, stage, lab)
      lines = dropNodeChecks(lines)
      const withLab = pyFiles.length && !codeLab ? addCodeLab(lines, stage, pyFiles) : null
      if (withLab) [lines, codeLab] = [withLab, true]
      const text = tidy(promote(escapeSequenceSemicolons(britishProse(lines))))
      const markdown = `${HEADER}# ${lessonTitle(stage, part)}\n\n${text}\n`
      const hit = markdown.match(PLACEHOLDER)
      if (hit) throw new Error(`${stage.rel}/guide.md, part ${part.n}: placeholder "${hit[0]}"`)
      if (wordCount(markdown) <= WORD_LIMIT) {
        files.set(partFile(stage, part), markdown)
        continue
      }
      const cut = text.search(/^## Interview\b/m)
      if (cut === -1) throw new Error(`${stage.rel}/guide.md, part ${part.n}: over ${WORD_LIMIT} words with no "Interview" heading to split at`)
      const extra = { n: `${part.n}b`, title: 'Staff interview practice' }
      files.set(partFile(stage, part), `${HEADER}# ${lessonTitle(stage, part)}\n\n${text.slice(0, cut).trim()}\n`)
      files.set(partFile(stage, extra), `${HEADER}# ${lessonTitle(stage, extra)}\n\n${text.slice(cut).trim()}\n`)
      stage.extra = { after: part.n, part: extra }
    }
    if (pyFiles.length && !codeLab) throw new Error(`${stage.rel}: labs/ has Python files but guide.md gives no \`python3 …/labs/test_*.py\` command`)
    if (lab && !linked) throw new Error(`${stage.rel}/guide.md: never links its lab, so no lesson would show it`)
  }

  checkLinks(files)
  for (const [file, markdown] of files) {
    if (wordCount(markdown) > WORD_LIMIT) throw new Error(`${OUT_REL}/${file}: ${wordCount(markdown)} words, over ${WORD_LIMIT}`)
  }

  const out = join(REPO_ROOT, OUT_REL)
  rmSync(out, { recursive: true, force: true })
  for (const [file, markdown] of files) {
    mkdirSync(dirname(join(out, file)), { recursive: true })
    writeFileSync(join(out, file), markdown)
  }
  const source = {
    course: COURSE,
    commit,
    stages: stages.map((s) => ({
      dir: s.dir,
      title: s.title,
      lessons: s.parts.flatMap((p) => [p, ...(s.extra?.after === p.n ? [s.extra.part] : [])]).map((p) => ({ file: partFile(s, p), title: lessonTitle(s, p) })),
    })),
  }
  writeFileSync(join(out, 'source.json'), `${JSON.stringify(source, null, 2)}\n`)
  const labsOut = join(REPO_ROOT, LABS_REL)
  rmSync(labsOut, { recursive: true, force: true })
  for (const [dir, html] of labs) {
    mkdirSync(join(labsOut, dir), { recursive: true })
    writeFileSync(join(labsOut, dir, 'lab.html'), html)
  }
  return { stages: stages.length, lessons: files.size, labs: labs.size, commit }
}

