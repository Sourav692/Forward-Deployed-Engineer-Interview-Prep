/** "Handle Overload and Fair Scheduling" → "Handle overload and fair scheduling"; acronyms stay. */
export function sentenceCase(title) {
  const lower = (word) => (/^[A-Z0-9]{2,}s?$/.test(word) ? word : word.toLowerCase())
  const text = title
    .split(' ')
    .map((word) => word.split('-').map(lower).join('-'))
    .join(' ')
  return britishText(text.charAt(0).toUpperCase() + text.slice(1))
}

/** The anchor python-markdown's toc extension gives a heading (the course renders its HTML with it). */
const tocSlug = (text) =>
  text
    .normalize('NFKD')
    .replace(/[^\x00-\x7f]/g, '')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .toLowerCase()
    .replace(/[-\s]+/g, '-')

/** Calls `fn(line, index)` for each line outside fenced code blocks. */
function eachProseLine(lines, fn) {
  let fence = null
  lines.forEach((line, i) => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/)
    if (fence) {
      if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length) fence = null
      return
    }
    if (marker) fence = marker[1]
    else fn(line, i)
  })
}

const HEADING = /^(#{1,6})\s+(.*?)\s*#*\s*$/

// ------------------------------------------------------------------ parse

/**
 * One stage: its folder, title, preamble and five parts. Each part keeps its lines (part heading
 * removed, sections in DROPPED_SECTIONS cut) and the original headings it holds.
 */
function parseStage(dir) {
  const rel = `${COURSE}/stages/${dir}`
  const lines = readFileSync(join(REPO_ROOT, rel, 'guide.md'), 'utf8').split('\n')
  const h1 = lines[0].match(/^# Stage (\d+): (.+)$/)
  if (!h1) throw new Error(`${rel}/guide.md: first line is not "# Stage N: <title>"`)
  const starts = []
  eachProseLine(lines, (line, i) => {
    const m = line.match(/^## (\d+)\. (.+)$/)
    if (m) starts.push({ i, n: Number(m[1]), title: m[2] })
  })
  if (starts.length !== 5 || starts.some((s, k) => s.n !== k + 1)) {
    throw new Error(`${rel}/guide.md: expected "## 1." to "## 5." part headings, found ${starts.map((s) => s.n).join(', ')}`)
  }
  const parts = starts.map((s, k) => {
    const body = dropSections(lines.slice(s.i + 1, starts[k + 1]?.i ?? lines.length))
    return { n: s.n, heading: `${s.n}. ${s.title}`, title: sentenceCase(s.title), lines: body, sections: sectionsOf(body) }
  })
  return {
    dir,
    rel,
    out: dir.replace(/-/g, '_'),
    title: sentenceCase(h1[2]),
    preamble: lines.slice(1, starts[0].i),
    parts,
  }
}

/** Cuts each heading in DROPPED_SECTIONS with everything under it. */
function dropSections(lines) {
  // `cut` is the level of the dropped heading while inside its section; fenced lines follow it.
  const prose = new Set()
  eachProseLine(lines, (_, i) => prose.add(i))
  let cut = null
  return lines.filter((line, i) => {
    const m = prose.has(i) && line.match(HEADING)
    if (m && cut && m[1].length <= cut) cut = null
    if (m && DROPPED_SECTIONS.includes(m[2])) cut = m[1].length
    return !cut
  })
}

/** Each original heading of a part body (### and deeper) with the `### ` section that holds it. */
function sectionsOf(lines) {
  const out = []
  let section = null
  eachProseLine(lines, (line) => {
    const m = line.match(HEADING)
    if (!m) return
    if (m[1].length === 3) section = m[2]
    out.push({ level: m[1].length, text: m[2], section })
  })
  return out
}

