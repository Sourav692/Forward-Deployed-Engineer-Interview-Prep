/** The parts of a module page: its overview and its interview questions. */
export function splitModulePage(md) {
  const lines = md.replace(/\n---\n\*Previous:[\s\S]*$/, '\n').split('\n')
  const meta = lines.findIndex((l) => /^\*Part [IVX]+ · /.test(l))
  if (meta !== -1) lines.splice(meta, 1)
  const sections = lines.join('\n').split(/(?=^## )/m)
  const interview = sections.find((s) => s.startsWith('## Interview Spotlight'))
  const overview = sections
    .filter((s) => s !== interview && !s.startsWith('## Lessons\n'))
    .join('')
    .replace(/ Each idea has a page in the folder of the lesson that teaches it, listed under \[Lessons\]\([^)]*\)\. This page has the overview, the interview questions and the takeaways\./, '')
  if (!interview) throw new Error('no "## Interview Spotlight" section')
  const [heading, ...body] = interview.split('\n')
  return { overview, interview: `# Interview questions\n\n${body.join('\n').trim()}\n`, spotlight: heading.slice(3) }
}

// How a word in a notebook file name is spelled on the site, where its case matters. Keep in
// step with CASED in the course's scripts/export_site_curriculum.py.
const CASED = Object.fromEntries([
  ...['a2a', 'ai', 'api', 'aws', 'crag', 'ec2', 'gpt', 'hf', 'json', 'llm', 'mcp', 'pdf', 'rag', 'sql', 'sse', 'ui', 'url'].map((w) => [w, w.toUpperCase()]),
  ['apis', 'APIs'], ['llms', 'LLMs'], ['python', 'Python'], ['flask', 'Flask'], ['groq', 'Groq'], ['openai', 'OpenAI'],
  ['langchain', 'LangChain'], ['langgraph', 'LangGraph'], ['llamaindex', 'LlamaIndex'], ['hyde', 'HyDE'],
])

/** A readable title for a notebook file: `02a_creating_an_mcp_server.ipynb` is "Creating an MCP server". */
export function fileTitle(name) {
  const stem = name.replace(/\.[^.]+$/, '').replace(/^\d+[a-z]?_/, '')
  const words = stem.split(/[_\-\s]+/).filter(Boolean)
  // A name typed all in capitals (`01a_AGENTIC_RAG_ARCHITECTURES.md`) reads as normal words; in a mixed
  // name a capitalised word is an acronym (`LCEL_Introduction`) and stays.
  const shouting = words.every((w) => w === w.toUpperCase())
  const title = words.map((w) => CASED[w.toLowerCase()] ?? (shouting ? w.toLowerCase() : w)).join(' ')
  return britishText(title.charAt(0).toUpperCase() + title.slice(1))
}

/**
 * A lesson page without its header line and footer. Its notebooks move to a "Run the notebooks"
 * section before Key Takeaways, each with a GitHub and a Colab link (the Colab target is
 * `colab:<course path>`, which `link` resolves). A notebook that names a vendor platform stays in
 * the course and off the site (site-text-edits.mjs).
 */
export function trimLessonPage(md) {
  let section = ''
  const body = md
    .replace(/\n---\n\*Previous:[\s\S]*$/, '\n')
    .replace(/^\*\[M\d+ theory\]\([^)]*\) · Lesson [\d.]+ · (?:Notebooks: (.*?) · )?\[All theory pages\]\([^)]*\)\*\n?/m, (_, nbs) => {
      const kept = (nbs ?? '').split(/, (?=\[`)/).filter((nb) => nb && !namesVendor(nb))
      section = notebookSection(kept)
      return ''
    })
  if (!section) return body
  const at = body.indexOf('\n## Key Takeaways')
  if (at < 0) return body.trim() ? `${body.trimEnd()}\n\n${section}` : section
  return `${body.slice(0, at)}\n${section}${body.slice(at)}`
}

/** The "Run the notebooks" section for header entries such as "[`01b_tool_use.ipynb`](path) (optional)". */
function notebookSection(entries) {
  if (!entries.length) return ''
  const rows = entries.map((entry) => {
    const [, file, target, rest] = entry.match(/^\[`([^`]+)`\]\(([^)\s]+)\)(.*)$/)
    const optional = rest.includes('optional') ? ' (optional)' : ''
    const colab = file.endsWith('.ipynb') ? `[Open in Colab](colab:${target})` : 'Run locally'
    return `| ${fileTitle(file)}${optional} | [Open on GitHub](${target}) | ${colab} |`
  })
  return [
    '## Run the notebooks',
    '',
    'The code for this lesson is in these notebooks. Colab runs one in your browser: install the packages its first cell imports and set the API keys it reads. To run every notebook as written, clone the repository and use its uv environment.',
    '',
    '| Notebook | GitHub | Colab |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n')
}

const ROMAN = { I: 1, V: 5, X: 10 }
const roman = (r) => [...r].reduce((n, c, i) => (ROMAN[c] < (ROMAN[r[i + 1]] ?? 0) ? n - ROMAN[c] : n + ROMAN[c]), 0)

/**
 * Rewrites the course's numbering into the site's: `moduleCode('13')` and `partCode(6)` give the
 * site codes (or null, leaving the text alone). `label` also maps a link whose whole text is "13.2".
 */
export function makeRenumber(moduleCode, partCode) {
  const lesson = (word, n, m) => {
    const code = moduleCode(n)
    return code ? `${word} ${Number(m)} of ${code}` : null
  }
  return (text, label = false) => {
    if (label && /^\d{1,2}\.\d{1,2}$/.test(text)) {
      const [n, m] = text.split('.')
      return lesson('lesson', n.padStart(2, '0'), m) ?? text
    }
    return text
      .replace(/\b([Ll]essons) (\d{1,2})\.(\d{1,2})( and | to | or |, )(\d{1,2})\.(\d{1,2})\b/g, (all, w, n1, m1, sep, n2, m2) => {
        const [a, b] = [moduleCode(n1.padStart(2, '0')), moduleCode(n2.padStart(2, '0'))]
        if (!a || !b) return all
        return a === b ? `${w} ${Number(m1)}${sep}${Number(m2)} of ${a}` : `${w.slice(0, -1)} ${Number(m1)} of ${a}${sep}lesson ${Number(m2)} of ${b}`
      })
      .replace(/\b(in|from) (\d{1,2})\.(\d{1,2})(?= (?:does|do|did|shows|showed|uses|used|builds|built)\b)/g, (all, w, n, m) => {
        const code = moduleCode(n.padStart(2, '0'))
        return code ? `${w} lesson ${Number(m)} of ${code}` : all
      })
      .replace(/\b([Ll]esson|[Nn]otebook) (\d{1,2})\.(\d{1,2})\b/g, (all, w, n, m) => lesson(w, n.padStart(2, '0'), m) ?? all)
      .replace(/(?<![\w/[.])M(\d{2})\.(\d{1,2})\b/g, (all, n, m) => lesson('lesson', n, m) ?? all)
      .replace(/(?<![\w/[.])M(\d{2})(?![\d.]?\d)\b/g, (all, n) => moduleCode(n) ?? all)
      .replace(/\bPart ([IVX]+)\b/g, (all, r) => partCode(roman(r)) ?? all)
  }
}

/** Site codes for the course's modules (by two-digit number) and parts (by number), from rag-tracks.ts. */
function siteCodes() {
  const modules = new Map()
  const parts = new Map()
  for (const lesson of RAG_LESSONS.filter((l) => l.source.endsWith('/00_overview.md'))) {
    const [part, mod] = lesson.source.split('/').slice(-3, -1)
    const home = RAG_MODULES.find((m) => m.slug === lesson.home)
    modules.set(mod.slice(1, 3), home.code)
    parts.set(Number(part.slice(1, 3)), RAG_TRACKS.find((t) => t.slug === home.track).code)
  }
  return makeRenumber((n) => modules.get(n) ?? null, (k) => parts.get(k) ?? null)
}

/** Headings outside fences, in order. */
function headingsOf(md) {
  const out = []
  let fence = false
  for (const line of md.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence
    const m = !fence && line.match(/^(#{1,6})\s+(.*?)\s*$/)
    if (m) out.push({ level: m[1].length, text: m[2] })
  }
  return out
}

/** GitHub anchor of each heading -> the site id of its `## ` section ('' above the first). */
function anchorIds(md) {
  const ids = new Map()
  let section = ''
  for (const h of headingsOf(md)) {
    if (h.level <= 2 && h.level > 1) section = `lesson-${readingSlug(siteHeading(h.text)) || 'section'}`
    ids.set(githubSlug(h.text), h.level === 1 ? '' : section)
  }
  return ids
}

// ------------------------------------------------------------------ import

function git(from, ...args) {
  return execFileSync('git', ['-C', from, ...args], { encoding: 'utf8' }).trim()
}

/**
 * The course page a vendored file comes from: `<part>/<module>/00_overview.md` and
 * `99_interview_questions.md` from the module page, `NN_<lesson>.md` from that lesson's page
 * in whichever tier folder holds it.
 */
export function coursePage(from, vendored) {
  const [part, mod, file] = vendored.split('/').slice(-3)
  const stem = file.replace(/\.md$/, '')
  const theory = (tier) => join(from, part, mod, tier, 'theory')
  if (stem === '00_overview' || stem === '99_interview_questions') return join(theory('mandatory'), 'README.md')
  const hits = TIERS.map((tier) => join(theory(tier), stem, 'README.md')).filter((f) => existsSync(f))
  if (hits.length !== 1) throw new Error(`${vendored}: ${hits.length ? 'a lesson page in both tiers' : 'no lesson page'} in ${part}/${mod}`)
  return hits[0]
}

export function importTheory(from) {
  if (!existsSync(join(from, 'THEORY.md'))) throw new Error(`${from} is not a rag-agents-engineering checkout`)
  if (git(from, 'status', '--porcelain', '--', ':(glob)p[0-9][0-9]_*/m[0-9][0-9]_*/*/theory/**'))
    throw new Error('the theory pages have uncommitted changes; commit them first')
  const commit = git(from, 'rev-parse', 'HEAD')

  // Every page the export names, its vendored path and its anchors.
  const pages = [] // { src, out, md, mod }
  const modules = new Map() // module folder -> { dir, readme, overview }
  for (const lesson of RAG_LESSONS) {
    const out = join(SITE, '..', lesson.source)
    if (dirname(dirname(dirname(out))) !== OUT) throw new Error(`${lesson.source}: not a <part>/<module>/<page>.md under ${posix(relative(SITE, OUT))}`)
    const [part, mod] = lesson.source.split('/').slice(-3, -1)
    const src = coursePage(from, lesson.source)
    if (basename(out) === '00_overview.md') {
      const { overview, interview, spotlight } = splitModulePage(readFileSync(src, 'utf8'))
      modules.set(mod, { dir: join(from, part, mod), readme: src, overview: out })
      pages.push({ src, out, md: overview, mod })
      pages.push({ src, out: join(dirname(out), '99_interview_questions.md'), md: interview, mod, spotlight })
    } else if (basename(out) !== '99_interview_questions.md') {
      pages.push({ src, out, md: trimLessonPage(readFileSync(src, 'utf8')), mod })
    }
  }
  const moduleOf = new Map([...modules].map(([mod, m]) => [m.readme, mod]))
  // (source file, GitHub anchor) -> (vendored file, site id). A module page's anchors may
  // sit in either half, and a concept anchor on it may name a heading on a lesson page.
  const anchors = new Map()
  for (const p of pages) {
    const known = anchors.get(p.src) ?? new Map()
    for (const [gh, id] of anchorIds(p.md)) known.set(gh, { out: p.out, id })
    if (p.spotlight) known.set(githubSlug(p.spotlight), { out: p.out, id: '' })
    anchors.set(p.src, known)
  }
  const byNum = new Map([...modules].map(([mod, m]) => [mod.slice(1, 3), m]))
  const renumber = siteCodes()

  const errors = []
  const copies = new Map() // source file -> public file
  for (const p of pages) {
    const where = posix(relative(from, p.src))
    const rel = (target) => posix(relative(dirname(p.out), target))
    const findAnchor = (src, anchor) => {
      const hit =
        anchors.get(src)?.get(anchor) ??
        (moduleOf.has(src)
          ? pages.filter((q) => q.mod === moduleOf.get(src)).map((q) => anchors.get(q.src).get(anchor)).find(Boolean)
          : undefined)
      if (!hit) errors.push(`${where}: no heading for #${anchor} in ${posix(relative(from, src))}`)
      return hit
    }
    const link = (target) => {
      if (target.startsWith('colab:')) return link(target.slice(6)).replace(`https://github.com/${REPO}/blob/`, `https://colab.research.google.com/github/${REPO}/blob/`)
      if (/^(https?:|mailto:)/.test(target)) return target
      const [path, anchor] = target.split('#')
      const abs = path ? resolve(dirname(p.src), decodeURI(path)) : p.src
      if (anchors.has(abs)) {
        const hit = anchor ? findAnchor(abs, anchor) : { out: pages.find((q) => q.src === abs).out, id: '' }
        if (!hit) return target
        const file = hit.out === p.out ? '' : rel(hit.out)
        return `${file}${hit.id ? `#${hit.id}` : ''}` || '#'
      }
      if (!existsSync(abs)) {
        errors.push(`${where}: broken link ${target}`)
        return target
      }
      const course = posix(relative(from, abs))
      const lab = course.match(LAB_PATH)
      if (lab) {
        copies.set(abs, join(LABS, lab[1], lab[2]))
        return `/labs/rag/${lab[1]}/${lab[2]}`
      }
      const svg = course.match(SVG_PATH)
      if (svg) {
        copies.set(abs, join(ASSETS, svg[1], svg[2]))
        return `/learn-assets/rag/${svg[1]}/${svg[2]}`
      }
      return `https://github.com/${REPO}/${statSync(abs).isDirectory() ? 'tree' : 'blob'}/main/${course}${anchor ? `#${anchor}` : ''}`
    }
    const moduleLink = (code) => {
      const m = byNum.get(code.slice(1))
      return m && basename(m.dir) !== p.mod ? `[${renumber(code)}](${rel(m.overview)})` : null
    }
    let md = p.md
      .replace(/^```mermaid\n(?:(?!```)[\s\S])*```\n<!-- animated: (\S+) -->$/gm, (_, anim) => {
        const file = resolve(dirname(p.src), anim)
        if (!existsSync(file)) {
          errors.push(`${where}: animated diagram ${anim} is missing`)
          return ''
        }
        try {
          return `\`\`\`animated\n${siteAnimation(readFileSync(file, 'utf8'), posix(relative(from, file)))}\n\`\`\``
        } catch (e) {
          errors.push(`${where}: ${e.message}`)
          return ''
        }
      })
      .replace(/^<!-- lab: (\S+) -->$/gm, (_, lab) => {
        const file = resolve(dirname(p.src), lab)
        const title = existsSync(file) ? readFileSync(file, 'utf8').match(/<title>([\s\S]*?)<\/title>/)?.[1].trim() : null
        if (!title) errors.push(`${where}: lab ${lab} is missing or has no <title>`)
        return `\`\`\`lab\nsrc: ${link(lab)}\ntitle: ${title}\n\`\`\``
      })
    for (const [mark] of md.matchAll(/^<!-- animated: \S+ -->$/gm)) errors.push(`${where}: ${mark} does not follow a Mermaid diagram`)
    md = mapProseLines(md, (line) => transformLine(line, { link, moduleLink, renumber }), {
      raw: fileNamesAsTitles,
      fenced: (line, lang) => renumberDiagram(line, lang, renumber),
    })
    if (PLACEHOLDER.test(md)) errors.push(`${where}: placeholder ${md.match(PLACEHOLDER)[0]}`)
    md = siteText(posix(relative(join(SITE, '..'), p.out)), md)
    p.md = `${HEADER}${md.replace(/\n{3,}/g, '\n\n').trim()}\n`
  }
  if (errors.length) throw new Error(`${errors.length} problem(s):\n  ${errors.join('\n  ')}`)

  // Labs in a module are all copied, linked or not, so "Open full screen" never 404s.
  for (const [mod, m] of modules) {
    for (const tier of TIERS) {
      const theory = join(m.dir, tier, 'theory')
      for (const lesson of existsSync(theory) ? readdirSync(theory) : []) {
        const dir = join(theory, lesson, 'interactive')
        if (existsSync(dir)) for (const f of readdirSync(dir).filter((f) => f.endsWith('.html'))) copies.set(join(dir, f), join(LABS, mod, f))
      }
    }
  }
  for (const dir of [OUT, ASSETS, LABS]) rmSync(dir, { recursive: true, force: true })
  for (const p of pages) {
    mkdirSync(dirname(p.out), { recursive: true })
    writeFileSync(p.out, p.md)
  }
  for (const [src, dest] of copies) {
    mkdirSync(dirname(dest), { recursive: true })
    if (dest.endsWith('.html')) writeFileSync(dest, siteLab(readFileSync(src, 'utf8'), posix(relative(from, src))))
    else cpSync(src, dest)
  }
  writeFileSync(join(OUT, 'source.json'), `${JSON.stringify({ repo: REPO, commit }, null, 2)}\n`)
  writeFileSync(
    join(OUT, 'README.md'),
    '# RAG & Agents Engineering theory (vendored)\n\n' +
      `Generated from [${REPO}](https://github.com/${REPO}) at the commit in \`source.json\` by ` +
      '`site/scripts/rag-theory-import.mjs`. Do not edit these files: change the theory pages in the course ' +
      'repository, commit there, then run `npm run import:rag-theory -- --from <path to the course repo>` from `site/`.\n',
  )
  return { pages: pages.length, modules: modules.size, copies: copies.size, commit }
}

if (import.meta.main) {
  const at = process.argv.indexOf('--from')
  if (at === -1 || !process.argv[at + 1]) {
    console.error('usage: node scripts/rag-theory-import.mjs --from <path to rag-agents-engineering>')
    process.exit(2)
  }
  try {
    const r = importTheory(resolve(process.argv[at + 1]))
    console.log(`rag theory: ${r.pages} pages from ${r.modules} modules, ${r.copies} labs and figures, commit ${r.commit.slice(0, 7)}`)
  } catch (error) {
    console.error(`rag theory import failed: ${error.message}`)
    process.exit(1)
  }
}
