// ------------------------------------------------------------------ text transforms

/** British spelling for every word of `text`, leaving allowed names, paths and identifiers. */
export function britishText(text) {
  const kept = []
  for (const [re] of SPELLING_ALLOWED) text = text.replace(re, (m) => `\u0000${kept.push(m) - 1}\u0000`)
  text = text.replace(/\S+/g, (tok) => (/[_/\\]/.test(tok) ? tok : tok.replace(/[A-Za-z]+/g, britishSpelling)))
  return text.replace(/\u0000(\d+)\u0000/g, (_, i) => kept[i])
}

/** A heading's text as the site shows it. */
const siteHeading = (text) => (text.trim() === 'TL;DR' ? 'In short' : britishText(text))

/**
 * Maps every line outside fenced code through `fn`, with inline code spans masked so a
 * link whose text is code (`[`a.ipynb`](…)`) still reaches `fn` whole. `raw` sees the
 * unmasked line first; `fenced(line, lang)` maps lines inside a fence (default: unchanged).
 */
function mapProseLines(md, fn, { raw = (l) => l, fenced = (l) => l } = {}) {
  let fence = null
  let lang = ''
  return md
    .split('\n')
    .map((line) => {
      const marker = line.match(/^\s*(`{3,}|~{3,})(\w*)/)
      if (fence) {
        if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length && !marker[2]) {
          fence = null
          return line
        }
        return fenced(line, lang)
      }
      if (marker) {
        fence = marker[1]
        lang = marker[2]
        return line
      }
      const code = []
      const masked = raw(line).replace(/`+[^`\n]*?`+/g, (m) => `\u0001${code.push(m) - 1}\u0001`)
      return fn(masked).replace(/\u0001(\d+)\u0001/g, (_, i) => code[i])
    })
    .join('\n')
}

/**
 * Course file names in prose as readable titles (PQ-07): a link whose text is a file name
 * (`[`deep_agent_overview.md`](…)`) and a numbered course file named in code
 * (`01a_AGENTIC_RAG_ARCHITECTURES.md`). Data files the lessons work with (`refunds.md`) stay.
 */
export function fileNamesAsTitles(line) {
  return line
    .replace(/\[`([^`\n]+\.(?:ipynb|md|py))`\]\(/g, (_, file) => `[${fileTitle(basename(file))}](`)
    .replace(/`(\d{2}[a-z]?_[\w-]+\.(?:ipynb|md))`/g, (_, file) => `*${fileTitle(file)}*`)
}

/**
 * Course numbers inside a diagram: every line of a Mermaid fence, and only the text between
 * tags in an animated SVG fence, so path data such as `M20 42` is never read as a module code.
 */
export function renumberDiagram(line, lang, renumber) {
  if (lang === 'mermaid') return renumber(line)
  if (lang === 'animated') return line.replace(/(^|>)([^<]+)(?=<|$)/g, (_, open, text) => open + renumber(text))
  return line
}

/**
 * One line of prose: link targets get `link(target)`, internal link text and plain text
 * get British spelling, and a bare module code outside headings and links gets `moduleLink(code)`.
 */
export function transformLine(line, { link, moduleLink, renumber = (t) => t }) {
  const heading = line.match(/^#{1,6}\s+/)?.[0] ?? ''
  if (heading && line.slice(heading.length).trim() === 'TL;DR') return `${heading}In short`
  return (
    heading +
    line
      .slice(heading.length)
      .split(/(!?\[[^\]]*\]\([^)\s]+\))/g)
      .map((part, i) => {
        if (i % 2 === 1) {
          const [, bang, label, target] = part.match(/^(!?)\[([^\]]*)\]\(([^)\s]+)\)$/)
          return `${bang}[${/^https?:/.test(target) ? label : renumber(britishText(label), true)}](${link(target)})`
        }
        const text = britishText(part)
        if (heading) return renumber(text)
        return text
          .split(/(?<![\w/[.])(M\d{2})(?![\d.]?\d)\b/g)
          .map((bit, j) => (j % 2 === 1 ? (moduleLink(bit) ?? renumber(bit)) : renumber(bit)))
          .join('')
      })
      .join('')
  )
}

// ------------------------------------------------------------------ labs

const REQUESTS = /\bfetch\s*\(|XMLHttpRequest|WebSocket|EventSource|sendBeacon|\bimport\s*\(|\b(?:src|href)=["']?https?:|url\(\s*["']?https?:/

/** A lab as the site serves it: no Google Fonts, the site's tokens and glue script, no requests. */
export function siteLab(html, name) {
  const out = html
    .replace(/[ \t]*<link[^>]+fonts\.(?:googleapis|gstatic)\.com[^>]*>\n?/g, '')
    .replace('</head>', '<link rel="stylesheet" href="/labs/_site-tokens.css">\n<script src="/labs/_site-lab.js"></script>\n</head>')
  if (!out.includes('/labs/_site-lab.js')) throw new Error(`${name}: no </head> to add the site tokens to`)
  const request = out.match(REQUESTS)
  if (request) throw new Error(`${name}: makes a request (${request[0]}); labs must run offline`)
  return out
}

/**
 * An animated diagram (`diagrams/*.anim.html`) as the ```animated fence body (FE-12): the figure
 * without the file's comments, its text in British spelling. Fails on anything that could run
 * script or make a request; the only url() allowed is a reference to the figure's own markers.
 */
export function siteAnimation(html, name) {
  const fig = html.replace(/\s*<!--[\s\S]*?-->/g, '').trim()
  if (!fig.startsWith('<figure class="anim')) throw new Error(`${name}: not an animated figure`)
  const bad = fig.match(/<(?:script|iframe|object|embed|foreignObject)\b|\son[a-z]+\s*=|\s(?:src|href|xlink:href)\s*=|url\(\s*["']?(?!#)|```/i)
  if (bad) throw new Error(`${name}: ${bad[0]} is not allowed in an animated diagram`)
  return fig
    .replace(/>([^<]+)</g, (_, text) => `>${britishText(text)}<`)
    .replace(/\saria-label="([^"]*)"/g, (_, text) => ` aria-label="${britishText(text)}"`)
}

