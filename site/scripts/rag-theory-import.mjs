/**
 * Vendors the theory pages of the RAG & Agents Engineering course
 * (github.com/Sourav692/rag-agents-engineering, folder `theory/`) into
 * `01_Concept_Tutorials/RAG_Agents_Engineering/` (AI Engineering integration, task FE-01).
 * The course repository stays the place to edit them; this copy is regenerated, never edited.
 *
 *   npm run import:rag-theory -- --from ../../rag-agents-engineering
 *
 * Each module `theory/<part>/<module>/` becomes `<part>/<module>/`:
 *  - `README.md` splits into `00_overview.md` (everything but the Lessons table and the
 *    interview questions) and `99_interview_questions.md`; its meta line and footer go;
 *  - each lesson page `NN_<lesson>/README.md` becomes `NN_<lesson>.md`, its header line
 *    reduced to the notebooks and its previous/next footer dropped (the site has its own).
 * Transforms, outside code:
 *  - links between theory pages become relative links between the vendored files, which
 *    `learn.mjs` turns into /learn URLs; a heading anchor becomes the site's `lesson-…` id
 *    of its `## ` section. Labs link to /labs/rag/<module>/, SVG figures to
 *    /learn-assets/rag/<module>/ (both copied into public/), anything else in the course
 *    repository to GitHub. A link that resolves to nothing fails the import;
 *  - `<!-- lab: … -->` becomes a ```lab fence (src and title lines); `<!-- animated: … -->`
 *    markers are dropped, so the Mermaid diagram they follow shows;
 *  - American spellings become British (src/lib/spelling.ts), except the names it allows
 *    and external link titles; "TL;DR" headings become "In short"; a bare "M13" becomes a
 *    link to that module's overview.
 * The import fails on a placeholder (TODO, TBD, XXX, [FILL) and when the course
 * repository has uncommitted theory changes, so `source.json` names the exact commit.
 */
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, resolve, sep } from 'node:path'
import { britishSpelling, SPELLING_ALLOWED } from '../src/lib/spelling.ts'
import { githubSlug, readingSlug } from './learn.mjs'

const REPO = 'Sourav692/rag-agents-engineering'
const SITE = resolve(import.meta.dirname, '..')
const OUT = join(SITE, '..', '01_Concept_Tutorials', 'RAG_Agents_Engineering')
const ASSETS = join(SITE, 'public', 'learn-assets', 'rag')
const LABS = join(SITE, 'public', 'labs', 'rag')
const PLACEHOLDER = /\[FILL\b|\bTODO\b|\bTBD\b|\bXXX\b/
const HEADER = '<!-- Generated by site/scripts/rag-theory-import.mjs from rag-agents-engineering. Edit the source there. -->\n'
const posix = (p) => p.split(sep).join('/')

// ------------------------------------------------------------------ text transforms

/** British spelling for every word of `text`, leaving allowed names, paths and identifiers. */
export function britishText(text) {
  const kept = []
  for (const [re] of SPELLING_ALLOWED) text = text.replace(re, (m) => `\u0000${kept.push(m) - 1}\u0000`)
  text = text.replace(/\S+/g, (tok) => (/[_/\\]/.test(tok) ? tok : tok.replace(/[A-Za-z]+/g, britishSpelling)))
  return text.replace(/\u0000(\d+)\u0000/g, (_, i) => kept[i])
}

/** A heading's text as the site shows it. */
const siteHeading = (text) => (text.trim() === 'TL;DR' ? 'In short' : britishText(text))

/**
 * Maps every line outside fenced code through `fn`, with inline code spans masked so a
 * link whose text is code (`[`a.ipynb`](…)`) still reaches `fn` whole.
 */
function mapProseLines(md, fn) {
  let fence = null
  return md
    .split('\n')
    .map((line) => {
      const marker = line.match(/^\s*(`{3,}|~{3,})/)
      if (fence) {
        if (marker && marker[1][0] === fence[0] && marker[1].length >= fence.length) fence = null
        return line
      }
      if (marker) {
        fence = marker[1]
        return line
      }
      const code = []
      const masked = line.replace(/`+[^`\n]*?`+/g, (m) => `\u0001${code.push(m) - 1}\u0001`)
      return fn(masked).replace(/\u0001(\d+)\u0001/g, (_, i) => code[i])
    })
    .join('\n')
}

/**
 * One line of prose: link targets get `link(target)`, internal link text and plain text
 * get British spelling, and a bare module code outside headings and links gets `moduleLink(code)`.
 */
export function transformLine(line, { link, moduleLink }) {
  const heading = line.match(/^#{1,6}\s+/)?.[0] ?? ''
  if (heading && line.slice(heading.length).trim() === 'TL;DR') return `${heading}In short`
  return (
    heading +
    line
      .slice(heading.length)
      .split(/(!?\[[^\]]*\]\([^)\s]+\))/g)
      .map((part, i) => {
        if (i % 2 === 1) {
          const [, bang, label, target] = part.match(/^(!?)\[([^\]]*)\]\(([^)\s]+)\)$/)
          return `${bang}[${/^https?:/.test(target) ? label : britishText(label)}](${link(target)})`
        }
        const text = britishText(part)
        return heading ? text : text.replace(/(?<![\w/[.])M(\d{2})(?![\d.]?\d)\b/g, (code) => moduleLink(code) ?? code)
      })
      .join('')
  )
}

// ------------------------------------------------------------------ course pages

/** The parts of a module page: its overview and its interview questions. */
export function splitModulePage(md) {
  const lines = md.replace(/\n---\n\*Previous:[\s\S]*$/, '\n').split('\n')
  const meta = lines.findIndex((l) => /^\*Part [IVX]+ · /.test(l))
  if (meta !== -1) lines.splice(meta, 1)
  const sections = lines.join('\n').split(/(?=^## )/m)
  const interview = sections.find((s) => s.startsWith('## Interview Spotlight'))
  const overview = sections
    .filter((s) => s !== interview && !s.startsWith('## Lessons\n'))
    .join('')
    .replace(/ Each idea has a page in the folder of the lesson that teaches it, listed under \[Lessons\]\([^)]*\)\. This page has the overview, the interview questions and the takeaways\./, '')
  if (!interview) throw new Error('no "## Interview Spotlight" section')
  const [heading, ...body] = interview.split('\n')
  return { overview, interview: `# Interview questions\n\n${body.join('\n').trim()}\n`, spotlight: heading.slice(3) }
}

/** A lesson page without its header line (notebooks kept) and footer. */
export function trimLessonPage(md) {
  return md
    .replace(/\n---\n\*Previous:[\s\S]*$/, '\n')
    .replace(/^\*\[M\d+ theory\]\([^)]*\) · Lesson [\d.]+ · (?:Notebooks: (.*?) · )?\[All theory pages\]\([^)]*\)\*$/m, (_, nbs) =>
      nbs ? `*Notebooks: ${nbs}*` : '',
    )
}

/** Headings outside fences, in order. */
function headingsOf(md) {
  const out = []
  let fence = false
  for (const line of md.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) fence = !fence
    const m = !fence && line.match(/^(#{1,6})\s+(.*?)\s*$/)
    if (m) out.push({ level: m[1].length, text: m[2] })
  }
  return out
}

/** GitHub anchor of each heading -> the site id of its `## ` section ('' above the first). */
function anchorIds(md) {
  const ids = new Map()
  let section = ''
  for (const h of headingsOf(md)) {
    if (h.level <= 2 && h.level > 1) section = `lesson-${readingSlug(siteHeading(h.text)) || 'section'}`
    ids.set(githubSlug(h.text), h.level === 1 ? '' : section)
  }
  return ids
}

// ------------------------------------------------------------------ import

function git(from, ...args) {
  return execFileSync('git', ['-C', from, ...args], { encoding: 'utf8' }).trim()
}

export function importTheory(from) {
  const theory = join(from, 'theory')
  if (!existsSync(join(theory, 'README.md'))) throw new Error(`${from} is not a rag-agents-engineering checkout`)
  if (git(from, 'status', '--porcelain', '--', 'theory')) throw new Error('theory/ has uncommitted changes; commit them first')
  const commit = git(from, 'rev-parse', 'HEAD')

  // Every page, its vendored path and its anchors.
  const pages = [] // { src, out, md, module }
  const modules = new Map() // module folder -> { dir, overview }
  for (const part of readdirSync(theory).filter((d) => /^p\d\d_/.test(d)).sort()) {
    for (const mod of readdirSync(join(theory, part)).filter((d) => /^m\d\d_/.test(d)).sort()) {
      const dir = join(theory, part, mod)
      const readme = join(dir, 'README.md')
      if (!existsSync(readme)) continue
      const out = join(OUT, part, mod)
      const { overview, interview, spotlight } = splitModulePage(readFileSync(readme, 'utf8'))
      modules.set(mod, { dir, part, overview: join(out, '00_overview.md') })
      pages.push({ src: readme, out: join(out, '00_overview.md'), md: overview, mod })
      pages.push({ src: readme, out: join(out, '99_interview_questions.md'), md: interview, mod, spotlight })
      for (const lesson of readdirSync(dir).filter((d) => /^\d\d_/.test(d) && existsSync(join(dir, d, 'README.md'))).sort()) {
        const src = join(dir, lesson, 'README.md')
        pages.push({ src, out: join(out, `${lesson}.md`), md: trimLessonPage(readFileSync(src, 'utf8')), mod })
      }
    }
  }
  // (source file, GitHub anchor) -> (vendored file, site id). A module page's anchors may
  // sit in either half, and a concept anchor on it may name a heading on a lesson page.
  const anchors = new Map()
  for (const p of pages) {
    const known = anchors.get(p.src) ?? new Map()
    for (const [gh, id] of anchorIds(p.md)) known.set(gh, { out: p.out, id })
    if (p.spotlight) known.set(githubSlug(p.spotlight), { out: p.out, id: '' })
    anchors.set(p.src, known)
  }
  const byNum = new Map([...modules].map(([mod, m]) => [mod.slice(1, 3), m]))

  const errors = []
  const copies = new Map() // source file -> public file
  for (const p of pages) {
    const where = posix(relative(from, p.src))
    const rel = (target) => posix(relative(dirname(p.out), target))
    const findAnchor = (src, anchor) => {
      const hit =
        anchors.get(src)?.get(anchor) ??
        (basename(dirname(dirname(src))).startsWith('p') && src.endsWith('README.md')
          ? pages.filter((q) => dirname(dirname(q.src)) === dirname(src)).map((q) => anchors.get(q.src).get(anchor)).find(Boolean)
          : undefined)
      if (!hit) errors.push(`${where}: no heading for #${anchor} in ${posix(relative(from, src))}`)
      return hit
    }
    const link = (target) => {
      if (/^(https?:|mailto:)/.test(target)) return target
      const [path, anchor] = target.split('#')
      const abs = path ? resolve(dirname(p.src), decodeURI(path)) : p.src
      if (anchors.has(abs)) {
        const hit = anchor ? findAnchor(abs, anchor) : { out: pages.find((q) => q.src === abs).out, id: '' }
        if (!hit) return target
        const file = hit.out === p.out ? '' : rel(hit.out)
        return `${file}${hit.id ? `#${hit.id}` : ''}` || '#'
      }
      if (!existsSync(abs)) {
        errors.push(`${where}: broken link ${target}`)
        return target
      }
      const course = posix(relative(from, abs))
      const lab = course.match(/^theory\/[^/]+\/([^/]+)\/(?:.*\/)?interactive\/([^/]+\.html)$/)
      if (lab) {
        copies.set(abs, join(LABS, lab[1], lab[2]))
        return `/labs/rag/${lab[1]}/${lab[2]}`
      }
      const svg = course.match(/^theory\/[^/]+\/([^/]+)\/(.+\.svg)$/)
      if (svg) {
        copies.set(abs, join(ASSETS, svg[1], svg[2]))
        return `/learn-assets/rag/${svg[1]}/${svg[2]}`
      }
      return `https://github.com/${REPO}/${statSync(abs).isDirectory() ? 'tree' : 'blob'}/main/${course}${anchor ? `#${anchor}` : ''}`
    }
    const moduleLink = (code) => {
      const m = byNum.get(code.slice(1))
      return m && basename(m.dir) !== p.mod ? `[${code}](${rel(m.overview)})` : null
    }
    let md = p.md
      .replace(/^<!-- animated: \S+ -->\n?/gm, '')
      .replace(/^<!-- lab: (\S+) -->$/gm, (_, lab) => {
        const file = resolve(dirname(p.src), lab)
        const title = existsSync(file) ? readFileSync(file, 'utf8').match(/<title>([\s\S]*?)<\/title>/)?.[1].trim() : null
        if (!title) errors.push(`${where}: lab ${lab} is missing or has no <title>`)
        return `\`\`\`lab\nsrc: ${link(lab)}\ntitle: ${title}\n\`\`\``
      })
    md = mapProseLines(md, (line) => transformLine(line, { link, moduleLink }))
    if (PLACEHOLDER.test(md)) errors.push(`${where}: placeholder ${md.match(PLACEHOLDER)[0]}`)
    p.md = `${HEADER}${md.replace(/\n{3,}/g, '\n\n').trim()}\n`
  }
  if (errors.length) throw new Error(`${errors.length} problem(s):\n  ${errors.join('\n  ')}`)

  // Labs in a module are all copied, linked or not, so "Open full screen" never 404s.
  for (const [mod, m] of modules) {
    for (const lesson of readdirSync(m.dir)) {
      const dir = join(m.dir, lesson, 'interactive')
      if (existsSync(dir)) for (const f of readdirSync(dir).filter((f) => f.endsWith('.html'))) copies.set(join(dir, f), join(LABS, mod, f))
    }
  }
  for (const dir of [OUT, ASSETS, LABS]) rmSync(dir, { recursive: true, force: true })
  for (const p of pages) {
    mkdirSync(dirname(p.out), { recursive: true })
    writeFileSync(p.out, p.md)
  }
  for (const [src, dest] of copies) {
    mkdirSync(dirname(dest), { recursive: true })
    cpSync(src, dest)
  }
  writeFileSync(join(OUT, 'source.json'), `${JSON.stringify({ repo: REPO, commit }, null, 2)}\n`)
  writeFileSync(
    join(OUT, 'README.md'),
    '# RAG & Agents Engineering theory (vendored)\n\n' +
      `Generated from [${REPO}](https://github.com/${REPO}) at the commit in \`source.json\` by ` +
      '`site/scripts/rag-theory-import.mjs`. Do not edit these files: change the theory pages in the course ' +
      'repository, commit there, then run `npm run import:rag-theory -- --from <path to the course repo>` from `site/`.\n',
  )
  return { pages: pages.length, modules: modules.size, copies: copies.size, commit }
}

if (import.meta.main) {
  const at = process.argv.indexOf('--from')
  if (at === -1 || !process.argv[at + 1]) {
    console.error('usage: node scripts/rag-theory-import.mjs --from <path to rag-agents-engineering>')
    process.exit(2)
  }
  try {
    const r = importTheory(resolve(process.argv[at + 1]))
    console.log(`rag theory: ${r.pages} pages from ${r.modules} modules, ${r.copies} labs and figures, commit ${r.commit.slice(0, 7)}`)
  } catch (error) {
    console.error(`rag theory import failed: ${error.message}`)
    process.exit(1)
  }
}
