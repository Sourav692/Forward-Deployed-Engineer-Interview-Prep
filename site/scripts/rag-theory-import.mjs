/**
 * Vendors the theory pages of the RAG & Agents Engineering course
 * (github.com/Sourav692/rag-agents-engineering) into `01_Concept_Tutorials/RAG_Agents_Engineering/`
 * (AI Engineering integration, task FE-01).
 * The course repository stays the place to edit them; this copy is regenerated, never edited.
 *
 *   npm run import:rag-theory -- --from ../../rag-agents-engineering
 *
 * The pages to write are the `source` of every lesson in rag-tracks.ts (the course's export),
 * so export the curriculum first. A module `<part>/<module>/` in the course keeps its theory
 * in `mandatory/theory/` and `optional/theory/`, and becomes `<part>/<module>/` here:
 *  - its module page `mandatory/theory/README.md` splits into `00_overview.md` (everything but
 *    the Lessons table and the interview questions) and `99_interview_questions.md`; its meta
 *    line and footer go;
 *  - each lesson page `<tier>/theory/NN_<lesson>/README.md` becomes `NN_<lesson>.md`, its header
 *    line reduced to the notebooks and its previous/next footer dropped (the site has its own).
 * Transforms, outside code:
 *  - links between theory pages become relative links between the vendored files, which
 *    `learn.mjs` turns into /learn URLs; a heading anchor becomes the site's `lesson-…` id
 *    of its `## ` section. Labs link to /labs/rag/<module>/, SVG figures to
 *    /learn-assets/rag/<module>/ (both copied into public/), anything else in the course
 *    repository to GitHub. A link that resolves to nothing fails the import;
 *  - `<!-- lab: … -->` becomes a ```lab fence (src and title lines); a Mermaid diagram followed
 *    by `<!-- animated: … -->` becomes an ```animated fence holding that SVG figure (FE-12),
 *    which shows its finished frame without script, so the Mermaid version is not kept;
 *  - American spellings become British (src/lib/spelling.ts), except the names it allows
 *    and external link titles; "TL;DR" headings become "In short"; a bare "M13" becomes a
 *    link to that module's overview;
 *  - the course's own numbering becomes the site's (IA-08): "M13" becomes that module's site
 *    code (T6.2), "Lesson 13.2", "M13.2", "notebook 13.2" and a link labelled "13.2" become
 *    "lesson 2 of T6.2", and "Part VI" becomes that track's code (T7). The codes come from
 *    rag-tracks.ts, so export the curriculum before importing;
 *  - the lesson header's notebook links show readable titles, not file names (PQ-07).
 * Labs are rewritten for the site (Phase 2, FE-08): their Google Fonts links go (font-src 'self'
 * blocks them) and they load /labs/_site-tokens.css and /labs/_site-lab.js, which give them the
 * site's tokens, embedded mode and theme. A lab that would make a request (fetch, XHR, sockets,
 * dynamic import, an external src, href or url()) fails the import (SEC-02): labs run offline.
 * An animated figure that could run script or make a request (a script, an event handler, an
 * src or href, an external url()) fails the import, as a lab does.
 * The import fails on a placeholder (TODO, TBD, XXX, [FILL), on an exported page with no course
 * page, and when the course repository has uncommitted theory changes, so `source.json` names
 * the exact commit.
 */
