/**
 * Writes `src/lib/curriculum-index.ts`, the slice of the curriculum that browser code needs
 * (the progress store and the Learn progress islands): each module's slug, title, home lessons
 * and minutes, each track's modules, the lessons homed outside those lists, and RENAMED.
 *
 * Browser code must import this instead of `curriculum.ts`: a client module that imports
 * the full curriculum ships all of it (objectives, deliverables, probes, every lesson record)
 * in the shared chunk of every page, which put the lesson and module routes over their
 * bundle budget. `check:curriculum` fails when the committed index is stale, and `prebuild`
 * regenerates it.
 *
 *   node scripts/curriculum-index.ts
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { LESSONS, MODULES, RENAMED, TRACKS } from '../src/lib/curriculum.ts'

export const INDEX_FILE = resolve(import.meta.dirname, '../src/lib/curriculum-index.ts')

export function renderCurriculumIndex(): string {
  const modules = MODULES.map((m) => ({
    slug: m.slug,
    title: m.title,
    lessons: m.lessons,
    ...(m.estMinutes ? { estMinutes: m.estMinutes } : {}),
    ...(m.practiceMinutes ? { practiceMinutes: m.practiceMinutes } : {}),
  }))
  // A lesson's home is the module that lists it, except for the few that no module lists
  // (lessons retired with their module keep it as home).
  const listed = new Map(MODULES.flatMap((m) => m.lessons.map((l) => [l, m.slug] as const)))
  const otherHomes = Object.fromEntries(LESSONS.filter((l) => listed.get(l.slug) !== l.home).map((l) => [l.slug, l.home]))
  const tracks = TRACKS.map((t) => ({ slug: t.slug, modules: t.sections.flatMap((s) => s.modules) }))
  const json = (v: unknown) => JSON.stringify(v, null, 2)
  return `// Generated by scripts/curriculum-index.ts from curriculum.ts. Do not edit: run
// \`node scripts/curriculum-index.ts\` after changing the curriculum. Browser code imports this,
// never curriculum.ts, so pages do not ship the whole curriculum.

export type IndexModule = { slug: string; title: string; lessons: string[]; estMinutes?: number; practiceMinutes?: number }

export const INDEX_MODULES: IndexModule[] = ${json(modules)}

/** Lessons whose home is not the module that lists them, slug → home module. */
export const OTHER_HOMES: Record<string, string> = ${json(otherHomes)}

export const INDEX_TRACKS: { slug: string; modules: string[] }[] = ${json(tracks)}

export const INDEX_RENAMED: Record<string, string | null> = ${json(RENAMED)}
`
}

if (import.meta.main) {
  writeFileSync(INDEX_FILE, renderCurriculumIndex())
  console.log(`curriculum index: wrote ${INDEX_FILE}`)
}
