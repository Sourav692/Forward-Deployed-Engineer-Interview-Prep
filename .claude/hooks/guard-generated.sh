  */site/content/*|site/content/*|*/site/public/fde-last-day-prep/*|site/public/fde-last-day-prep/*)
    jq -n --arg f "$f" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: "deny",
